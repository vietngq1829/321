// Helper to find matching assets from script keywords
export function findMatchingStockAssets(text: string, count = 4): StockAsset[] {
  const lower = text.toLowerCase();
  const scored = CURATED_STOCK_ASSETS.map((asset) => {
    let score = 0;
    for (const tag of asset.tags) {
      if (lower.includes(tag)) {
        score += 3;
      }
    }
    if (lower.includes(asset.category.toLowerCase())) {
      score += 2;
    }
    return { asset, score };
  });

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, count).map((s) => s.asset);
}
